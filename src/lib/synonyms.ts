const norm = (t: string) =>
  t
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')

/** busca sinónimos para una palabra (normaliza la consulta) */
export function synonymsFor(word: string): string[] | null {
  const key = norm(word)
  const hit = WORD_SYNONYMS[key]
  return hit ? hit.filter((v): v is string => typeof v === 'string') : null
}
